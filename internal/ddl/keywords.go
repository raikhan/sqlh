// kw filters a keyword list for a dialect. An item "WORDS@tags" is only for
// the tagged dialects: p PostgreSQL, o Oracle, s SQLite, g the others.
// Untagged items are for all.
func kw(d sqlsplit.Dialect, items ...string) []string {
	tag := map[sqlsplit.Dialect]byte{sqlsplit.PostgreSQL: 'p', sqlsplit.Oracle: 'o', sqlsplit.SQLite: 's', sqlsplit.Generic: 'g'}[d]
	out := make([]string, 0, len(items))
	for _, it := range items {
		if i := strings.IndexByte(it, '@'); i >= 0 {
			if strings.IndexByte(it[i+1:], tag) < 0 {
				continue
			}
			it = it[:i]
		}
		out = append(out, it)
	}
	return out
}

func (p *parser) kw(items ...string) []string { return kw(p.d, items...) }

func (p *parser) kwSlot(items ...string) Slot { return Slot{Keywords: p.kw(items...)} }

