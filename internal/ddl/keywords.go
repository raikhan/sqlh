// Words lists the words of the keywords this package offers (for the
// formatter's keyword casing).
func Words() map[string]bool {
	out := map[string]bool{}
	lists := [][]string{
		statementStarts, createKinds, afterOrReplace, alterKinds, dropKinds, dropTail, alterTableActions,
		afterAdd, afterAlterColumn, columnConstraints, tableConstraintStarts, constraintKinds,
		referenceActions, referentialActions, constraintStates, tableTail, indexTail,
		indexElementTail, triggerTiming, triggerEvents, triggerTail, sequenceOptions, truncateTail,
		commentKinds, grantOnKinds, viewAfterName, alterViewActions, alterIndexActions,
		alterTriggerActions, alterTypeActions, defaultValues,
	}
	for _, m := range afterModifier {
		lists = append(lists, m)
	}
	for _, m := range typeContinuations {
		lists = append(lists, m)
	}
	for _, l := range lists {
		for _, it := range l {
			if i := strings.IndexByte(it, '@'); i >= 0 {
				it = it[:i]
			}
			for _, w := range strings.Fields(it) {
				out[w] = true
			}
		}
	}
	for k := range afterModifier {
		out[k] = true
	}
	return out
}
